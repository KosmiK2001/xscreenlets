/* Геометрия кнопок смены месяца в календаре.
 *
 * Координаты взяты из оригинального ClearCalendarScreenlet.py
 * (detect_button / update_buttons), поэтому проверяем не «что мы
 * придумали», а совпадение с оригиналом:
 *
 *   полоса:  x 0..15, y 0..15   курсор в ней показывает кнопки
 *   кнопки:  y 5.5..12.5
 *            x  8.5..15.5  назад   (1)
 *            x 18.5..25.5  сегодня (2)
 *            x 28.5..35.5  вперёд  (3)
 *
 * Печатает по строке на контрольную точку: ожидание и что вернул
 * cal_button_at / cal_in_strip.
 */
#include <stdio.h>
#include <stdbool.h>

#define CAL_BTN_Y0      5.5
#define CAL_BTN_Y1     12.5
#define CAL_BTN_X0      8.5
#define CAL_BTN_W       7.0
#define CAL_BTN_GAP     3.0
#define CAL_BTN_STRIP_W 100.0  /* ширина полосы: во весь кадр */
#define CAL_BTN_STRIP_H  15.0  /* высота полосы: 15 юнитов */

/* ---- интервал тика ----
 *
 * Именно здесь была причина «кнопки только по клику»:
 * альфа набирается на тике, и если при наведении тик уже
 * раз в 10 с, старт откладывается на 10 с, к моменту когда
 * курсор ушёл. Решается условием на наведение, а не на
 * саму альфу.
 */
#define CAL_FRAME_H     105  /* высота кадра: height=105*2 в оригинале */
#define CAL_BG_H        82  /* подложка: draw_rounded_rectangle(0,1,8,100,82) */
#define CAL_BTN_TICK_MS   100
#define CAL_TICK_IDLE_MS 10000

/* ---- высота кадра и смена месяца ----
 *
 * Кадр ПОСТОЯНЕН: base_h = CAL_FRAME_H (105), как в оригинале. Раньше
 * тест (и cal_event_to_canon) держали собственную копию формулы
 * 25 + rows*12 + 4, и когда отрисовка перешла на 105, hit-test
 * остался на 89: кнопки искались на 8 юнитов ниже нарисованных и не
 * ловились в 5-строчных месяцах, ловились в 6-строчных - «то
 * работает, то нет». Поэтому здесь НЕТ формулы: тест проверяет
 * сходимость с реальной геометрией, а не повторяет её.
 */
#define CAL_FRAME_H_TEST 105

/* Сентябрь 2026: 30 дней, начинается во вторник (start_col=1)
 * -> 6 строк. Октябрь 2026: 31 день, начинается в четверг
 * (start_col=3) -> 5 строк. То есть в паре месяцев высота
 * сетки разная. */
static int cal_rows(int start_col, int days)
{
	return (start_col + days - 1) / 7 + 1;
}


static bool cal_in_strip(double x, double y)
{
	return x >= 0.0 && x < CAL_BTN_STRIP_W
	       && y >= 0.0 && y <= CAL_BTN_STRIP_H;
	/* x < CAL_BTN_STRIP, а не x < CAL_BTN_Y1: полоса во всю
	 * ширину кадра, как update_buttons в оригинале. */
}

static int cal_button_at(double x, double y)
{
	int i;

	if (y < CAL_BTN_Y0 || y > CAL_BTN_Y1)
		return 0;
	for (i = 0; i < 3; i++) {
		double bx = CAL_BTN_X0 + i * (CAL_BTN_W + CAL_BTN_GAP);

		if (x >= bx && x <= bx + CAL_BTN_W)
			return i + 1;
	}
	return 0;
}

/* Один шаг анимации полосы. Возвращает false, когда таймер пора
 * снимать: полоса погасла и наведения больше нет.
 *
 * Именно таймер, а не общий tick календаря. Пока анимация жила
 * в tick'е (10 с), появление кнопок отставало на 6-9 секунд:
 * просьба «тикай чаще» применялась только когда текущий
 * интервал истекал. В оригинале update_buttons - отдельный
 * таймер на 100 мс, и здесь так же. */
static bool cal_alpha_step(double *alpha, int hover, int pressed)
{
	if (hover || pressed) {
		if (*alpha < 1.0) {
			*alpha += 0.2;
			if (*alpha > 1.0)
				*alpha = 1.0;
		}
	} else if (*alpha > 0.0) {
		*alpha -= 0.2;
		if (*alpha < 0.0)
			*alpha = 0.0;
	}
	return !(*alpha <= 0.0 && !hover && !pressed);
}

/* Сколько шагов нужно от alpha=0 при наведении. 0.2 за шаг,
 * значит полное проявление - ровно 5 шагов = 500 мс на таймере
 * 100 мс. Задержка в секунды означала бы, что таймер не тот. */
/* Прогоняет анимацию от нуля при наведении и считает шаги до
 * полной альфы. 5 шагов по 100 мс = 500 мс: столько нужно,
 * чтобы полоса проявилась, пока курсор в окне. */
static int check_fade_in(void)
{
	double a = 0.0;
	int steps = 0, keep;

	while ((keep = cal_alpha_step(&a, 1, 0)) && steps < 100) {
		steps++;
		if (a >= 1.0)
		break;
	}
	printf("  проявление с нуля: %d шагов по %d мс = %d мс  "
	       "%-26s %s\n", steps, CAL_BTN_TICK_MS, steps * CAL_BTN_TICK_MS,
	       "менее секунды",
	       (steps <= 6 && a >= 1.0) ? "OK" : "FAIL");
	if (!(a >= 1.0))
		return 1;
	return (steps <= 6) ? 0 : 1;
}

/* Уход курсора: полоса должна погаснуть и таймер сняться. */
static int check_fade_out(void)
{
	double a = 1.0;
	int steps = 0;
	bool keep = true;

	while (keep && steps < 100) {
		keep = cal_alpha_step(&a, 0, 0);
		steps++;
	}
	printf("  затухание с 1.0:   %d шагов, таймер %s  %-24s %s\n",
	       steps, keep ? "остаётся" : "снят",
	       "полоса гаснет и таймер снят",
	       (!keep && a <= 0.0 && steps <= 6) ? "OK" : "FAIL");
	return (!keep && a <= 0.0 && steps <= 6) ? 0 : 1;
}

int main(void)
{
	static const struct {
		double x, y;
		int btn;
		int strip;
		const char *what;
	} T[] = {
		/* середины кнопок оригинала */
		{ 12.0,  9.0, 1, 1, "назад, середина"},
		{ 22.0,  9.0, 2, 1, "сегодня, середина"},
		{ 32.0,  9.0, 3, 1, "вперёд, середина"},
		/* границы прямоугольников оригинала */
		{  8.5,  5.5, 1, 1, "назад, левый-верхний угол"},
		{ 15.5, 12.5, 1, 1, "назад, правый-нижний угол"},
		{ 28.5,  5.5, 3, 1, "вперёд, левый-верхний угол"},
		{ 35.5, 12.5, 3, 1, "вперёд, правый-нижний угол"},
		/* чуть за краями — не попадает */
		{  8.4,  9.0, 0, 1, "назад, левее на 0.1"},
		{ 35.6,  9.0, 0, 1, "вперёд, правее на 0.1"},
		{ 12.0,  5.4, 0, 1, "назад, выше на 0.1"},
		{ 12.0, 12.6, 0, 1, "назад, ниже на 0.1"},
		/* полоса видна, но кнопка не под курсором */
		{  3.0,  3.0, 0, 1, "пустое место полосы"},
		{  7.0, 14.0, 0, 1, "полоса, между кнопкой и краем"},
		/* вне полосы совсем */
		/* y вне полосы: кнопок нет, но полоса видна только пока
		 * курсор в y<=15, поэтому строка ниже y=40 вне полосы. */
		{ 20.0, 40.0, 0, 0, "сетка дня (ниже полосы)"},
		{ 60.0,  2.0, 0, 1, "справа от кнопок, но в полосе"},
		{120.0,  2.0, 0, 0, "за полосой"},
	};
	int fails = 0, i;
	unsigned n = sizeof T / sizeof T[0];

	for (i = 0; i < (int)n; i++) {
		int btn = cal_button_at(T[i].x, T[i].y);
		int strip = cal_in_strip(T[i].x, T[i].y) ? 1 : 0;
		int ok = (btn == T[i].btn) && (strip == T[i].strip);

		printf("  (%5.1f,%5.1f) btn=%d strip=%d  %-38s %s\n",
		       T[i].x, T[i].y, btn, strip, T[i].what, ok ? "OK" : "FAIL");
		if (!ok)
			fails++;
	}

	printf("\n  анимация полосы (свой 100-мс таймер):\n");
	/* Регресс на задержку 6-9 секунд: пока анимация жила в
	 * общем tick календаря, полоса проявлялась только когда
	 * истекал текущий 10-секундный интервал. Теперь шаги
	 * идут по 100 мс и полоса полностью видна за 500 мс. */
	fails += check_fade_in();
	fails += check_fade_out();
	printf("\n  высота кадра постоянна (как в оригинале):\n");
	/* В ClearCalendar высота окна задана один раз:
	 *   Screenlet.__init__(self, width=int(102*2),
	 *                       height=int(105*2), uses_theme=True)
	 *
	 * То есть 105 юнитов ВСЕГДА, независимо от числа строк.
	 * Раньше здесь было base_h = 25 + rows*12 + 4, то есть 89 при
	 * 5 строках и 101 при 6. Из-за этого:
	 *   - окно меняло размер при смене месяца;
	 *   - число 30/31 в 6-строчном месяце уезжало за подложку 82
	 *     (сетка кончается на 95).
	 *
	 * Проверяем, что при любом числе строк высота одна и та же и
	 * кадр выше и подложки, и самой нижней строки сетки. */
	{
		int sep = cal_rows(1, 30);   /* сентябрь 2026, 5 строк */
		int aug = cal_rows(6, 31);   /* август 2026, 6 строк  */
		int nov = cal_rows(6, 30);   /* ноябрь 2026, 6 строк  */
		int grid_bottom, bad;

		printf("  сентябрь строк=%d, август строк=%d, ноябрь строк=%d\n",
		       sep, aug, nov);

		/* Разные числа строк - разные месяцы, одна высота. */
		bad = (sep == aug) ? 1 : 0;   /* строки должны различаться */
		printf("  месяцы разной длины  %-36s %s\n",
		       "нужны разные числа строк",
		       bad ? "FAIL (тест не проверяет)" : "OK");
		fails += bad;

		/* Нижняя строка сетки: cy = 25 + row*12, плюс плашка 10. */
		grid_bottom = 25 + (aug - 1) * 12 + 10;
		bad = (CAL_FRAME_H >= grid_bottom) ? 0 : 1;
		printf("  кадр %d >= низ сетки %d (6 строк)  %-20s %s\n",
		       CAL_FRAME_H, grid_bottom, "число 30/31 в кадре",
		       bad ? "FAIL (вылезает)" : "OK");
		fails += bad;

		/* Кадр выше подложки: иначе число уезжает за неё. */
		bad = (CAL_FRAME_H > CAL_BG_H) ? 0 : 1;
		printf("  кадр %d > подложка %d  %-34s %s\n",
		       CAL_FRAME_H, CAL_BG_H, "сетка не свисает с подложки",
		       bad ? "FAIL" : "OK");
		fails += bad;
	}

	/* ---- СХОДИМОСТЬ ОТРИСОВКИ И HIT-TEST (регресс «кнопки то
	 * работают, то нет») ----
	 *
	 * Смысл: нарисованный прямоугольник кнопки переводится в
	 * экранные координаты геометрией ОТРИСОВКИ, а hit-test читает
	 * их своей геометрией - то есть проверяются ДВЕ независимые
	 * формулы, а не одна, применённая дважды (иначе round-trip
	 * сходится всегда и тест ничего не ловит).
	 *
	 * Именно так и вышло в коде: отрисовка брала кадр 105,
	 * hit-test держал 25+rows*12+4 (89 при 5 строках) -
	 * расхождение 8 юнитов при высоте кнопки 7, то есть мимо
	 * всегда; при 6 строках расхождение 2.0 - попадало. Отсюда
	 * «то работает, то нет» и работающий скролл (он координаты
	 * не считает).
	 *
	 * Проверка на КОНТРОЛЬНОЙ формуле: hit-test с багом (89) обязан
	 * дать промахи. Если и с ней всё «ловится» - тест пустой. */
	{
		struct { int w, h; } wins[] = {
			{ 228, 235 }, { 102, 105 }, { 300, 200 }, { 160, 400 }
		};
		const int draw_base = CAL_FRAME_H_TEST;   /* как в cal_draw */
		const int hit_base_buggy = 89;            /* 25 + 5*12 + 4 */
		int wi, i, miss_good = 0, miss_buggy = 0, empty = 0;

		printf("\nсходимость отрисовки и hit-test (две независимые формулы):\n");
		for (wi = 0; wi < (int)(sizeof(wins) / sizeof(wins[0])); wi++) {
			int w = wins[wi].w, h = wins[wi].h;

			/* miss: 0 = кнопка ловится, 1 = промах */
			for (i = 0; i < 3; i++) {
				double bx = CAL_BTN_X0 + i * (CAL_BTN_W + CAL_BTN_GAP);
				double cy = (CAL_BTN_Y0 + CAL_BTN_Y1) / 2.0;
				double sx, sy, k, ox, oy, kh, oxh, oyh, cx, cyy;
				int g, b;

				/* где кнопка НАРИСОВАНА (канон -> экран) */
				k = w / 102.0;
				if (h / (double)draw_base < k)
					k = h / (double)draw_base;
				ox = (w - 102.0 * k) / 2.0;
				oy = (h - draw_base * k) / 2.0;
				sx = ox + (bx + CAL_BTN_W / 2.0) * k;
				sy = oy + cy * k;

				/* 1) настоящий hit-test: та же геометрия */
				kh = k; oxh = ox; oyh = oy;
				cx = (sx - oxh) / kh;
				cyy = (sy - oyh) / kh;
				g = !(bx <= cx && cx <= bx + CAL_BTN_W
				      && CAL_BTN_Y0 <= cyy && cyy <= CAL_BTN_Y1);

				/* 2) контрольная, заведомо с багом */
				kh = w / 102.0;
				if (h / (double)hit_base_buggy < kh)
					kh = h / (double)hit_base_buggy;
				oxh = (w - 102.0 * kh) / 2.0;
				oyh = (h - hit_base_buggy * kh) / 2.0;
				cx = (sx - oxh) / kh;
				cyy = (sy - oyh) / kh;
				b = !(bx <= cx && cx <= bx + CAL_BTN_W
				      && CAL_BTN_Y0 <= cyy && cyy <= CAL_BTN_Y1);

				miss_good += g;
				miss_buggy += b;
			}
		}
		/* С кодом из репозитория промахов быть не должно. */
		empty = (miss_good != 0);
		printf("  настоящий hit-test: промахов %d из 12  %-18s %s\n",
		       miss_good, "клики ловятся", empty ? "FAIL" : "OK");
		fails += empty;
		/* Контроль: сломанная геометрия обязана давать промахи,
		 * иначе проверка выше ничего не доказывает. */
		empty = (miss_buggy == 0);
		printf("  контроль (баг 89): промахов %d из 12  %-15s %s\n",
		       miss_buggy, "баг ловится", empty ? "FAIL (тест пуст)" : "OK");
		fails += empty;
		printf("  высота кнопки %.1f, ошибка бага %.1f юнита -> %s\n",
		       CAL_BTN_Y1 - CAL_BTN_Y0, 8.0,
		       "мимо" );
	}



	printf("\nпровалов: %d\n", fails);
	return fails ? 1 : 0;
}