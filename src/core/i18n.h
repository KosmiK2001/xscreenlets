/* i18n.h - переводы интерфейса xscreenlets.
 *
 * Проект переведён на GPL-2.0-or-later, и английский язык является
 * исходным: строки в коде пишутся по-английски и оборачиваются в _().
 * Переводы лежат в каталоге po/ (файлы <lang>.po) и не требуют
 * правок в C.
 *
 * Почему _() определён здесь, а не через <glib/gi18n.h>: тот тянет за
 * собой зависимость от libintl и объявляет g_dgettext/dgettext с другой
 * семантикой. Здесь нужен один макрос без лишнего, при этом glibc
 * gettext() всё равно доступен - слинковывает его линкер.
 *
 * Практическое правило: оборачивать в _() ТОЛЬКО то, что видит
 * пользователь - gtk_label_new, заголовки окон, подсказки, выпадающие
 * списки. Ключи конфигов, пути, форматы printf и тексты, которые applet
 * показывает на рабочем столе (даты, имена лент), переводить нельзя:
 * их значение попадает в ~/.config/xscreenlets и в сообщения ядра.
 *
 * В коде макрос почти не встречается: подписи свойств переводятся в
 * xs_prop_row(), а xs_prop_add_bool/string/int/float/color/font/choices/
 * time сходятся именно туда. Это единственная точка перевода для всех
 * ~115 надписей настроек.
 */
#ifndef XSCREENLETS_I18N_H
#define XSCREENLETS_I18N_H

#ifdef HAVE_GETTEXT
#include <libintl.h>
#define _(String) gettext(String)
#else
/* Без gettext проект обязан собираться и работать: интерфейс останется
 * английским. Молчаливый вывод на stderr пугает пользователя. */
#define _(String) (String)
#endif

/* Вызывается один раз при старте демона, до создания окон.
 *
 * Язык берётся из gtk_get_default_language(), а не из переменных
 * LANG/LC_MESSAGES: в Gentoo типовая LC_MESSAGES выставлена в C, при
 * этом LANG может быть тоже C, и пользователь с русским интерфейсом
 * получил бы английский интерфейс демона. GLib решает это правильно,
 * потому что GTK-приложения настраивают язык именно так.
 */
void xs_i18n_init(void);

/* Каталог с переводами. Переопределяется переменной окружения
 * XSCREENLETS_LOCALEDIR - нужно для запуска из build/ без установки. */
const char *xs_i18n_localedir(void);

#endif /* XSCREENLETS_I18N_H */
